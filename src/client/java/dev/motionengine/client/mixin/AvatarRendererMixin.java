package dev.motionengine.client.mixin;

import com.mojang.blaze3d.vertex.PoseStack;
import dev.motionengine.client.bridge.MotionBridge;
import net.minecraft.client.renderer.entity.player.AvatarRenderer;
import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import net.minecraft.world.entity.Avatar;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * Hooks into AvatarRenderer (1.21.11, Mojang mappings). Full descriptors are used so the injections
 * target the real methods, not the generic bridge methods generated by javac.
 * The entity type parameter erases to its first bound, {@code Avatar}.
 */
@Mixin(AvatarRenderer.class)
public abstract class AvatarRendererMixin {

    @Inject(method = "extractRenderState(Lnet/minecraft/world/entity/Avatar;Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;F)V",
            at = @At("TAIL"))
    private void motionengine$extract(Avatar entity, AvatarRenderState state, float partialTick, CallbackInfo ci) {
        MotionBridge.extract(entity, state, partialTick);
    }

    @Inject(method = "setupRotations(Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;Lcom/mojang/blaze3d/vertex/PoseStack;FF)V",
            at = @At("TAIL"))
    private void motionengine$rootTransform(AvatarRenderState state, PoseStack poseStack, float bodyRot, float scale, CallbackInfo ci) {
        MotionBridge.applyRootTransform(state, poseStack);
    }
}
